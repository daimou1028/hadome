const COMPACT_PROMPT = [
  'これまでのやり取りを、**続きを書けるように**要約してください。',
  '利用者が何を頼んだか、こちらが何をしたかを、細かく残してください。',
  '',
  '**ツールは使わないでください。**必要なことは全部この対話の中に在ります。',
  '返すのは文章だけにしてください。',
  '',
  '次の 9 つの節に分けて書いてください:',
  '',
  '1. 頼まれたことと、その意図: 利用者の求めを漏らさず、細かく',
  '2. 出てきた技術の要点: 使った技術・仕組み・材料',
  '3. ファイルと中身: 読んだ／直した／作ったファイルを列挙し、**なぜそれが要ったか**と',
  '   大事な中身をそのまま添える',
  '4. 失敗と直し方: 出た失敗と、どう直したか。**利用者から受けた指摘は特に**',
  '5. 解いた問題と、途中のもの',
  '6. **利用者の発言を全部**（ツールの結果は除く）。ここが薄いと、頼まれたことが',
  '   分からなくなります',
  '7. 残っている仕事: 明示的に頼まれていて、まだ終わっていないもの',
  '8. いま何をしていたか: この要約を頼まれる直前にしていたことを、細かく',
  '9. 次の一歩: 直前の作業の続きとして何をするか。**利用者の直近の求めから',
  '   外れないこと。**どこで止まっていたかを、原文のまま引いて示してください',
  '',
  '古い頼みや、脇道の話を持ち出さないでください。',
].join('\n');

function handoffMessage(summary) {
  return [
    'これは、前の対話をここまで畳んだ要約です。**依頼ではありません。**',
    'ここから続きをやります。次の指示を待ってください。',
    '',
    '--- ここまでの要約 ---',
    String(summary || '').trim(),
    '--- 要約おわり ---',
  ].join('\n');
}

module.exports = { COMPACT_PROMPT, handoffMessage };
